// ─── Component ───────────────────────────────────────

interface QuickActionCardProps {
  action: QuickAction;
  index?: number;
}

export function QuickActionCard({ action, index = 0 }: QuickActionCardProps) {
  const content = (
    <motion.div
      variants={cardAppear}
      initial="hidden"
      animate="visible"
      transition={{ delay: 0.1 + index * 0.05 }}
      className={cn(
        "glass group flex items-center gap-3 rounded-xl px-4 py-3",
        "transition-all duration-[var(--duration-normal)]",
        "hover:bg-surface-hover hover:shadow-card-hover",
        action.disabled && "pointer-events-none opacity-50",
      )}
    >
      <div className="bg-accent-purple/10 text-accent-purple-light flex h-9 w-9 shrink-0 items-center justify-center rounded-lg">
        <ActionIcon iconKey={action.iconKey} />
      </div>
      <div className="min-w-0">
        <p className="text-text-primary text-sm font-medium">{action.title}</p>
        <p className="text-text-tertiary truncate text-xs">
          {action.description}
        </p>
      </div>
    </motion.div>
  );

  if (action.href && !action.disabled) {
    return <Link href={action.href}>{content}</Link>;
  }

  return content;
}
