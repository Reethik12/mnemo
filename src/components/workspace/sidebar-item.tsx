// ─── Component ───────────────────────────────────────

export function SidebarItem({
  label,
  subtitle,
  href,
  iconKey,
  badge,
  disabled,
  isExpanded,
}: SidebarItemProps) {
  const pathname = usePathname();
  const isActive = pathname === href;

  const content = (
    <div
      className={cn(
        "group relative flex items-center gap-3 rounded-lg px-3 py-2.5",
        "transition-all duration-[var(--duration-fast)]",
        isActive
          ? "bg-accent-purple/10 text-text-primary"
          : "text-text-secondary hover:text-text-primary hover:bg-white/5",
        disabled && "pointer-events-none opacity-40",
        !isExpanded && "justify-center px-0",
      )}
    >
      {/* Active indicator */}
      {isActive && (
        <div
          className="bg-accent-purple absolute top-1/2 left-0 h-5 w-0.5 -translate-y-1/2 rounded-full"
          aria-hidden="true"
        />
      )}

      <SidebarIcon iconKey={iconKey} />

      {isExpanded && (
        <>
          <div className="flex flex-1 flex-col truncate">
            <span className="truncate text-sm font-medium">{label}</span>
            {subtitle && (
              <span className="text-text-tertiary truncate text-[10px]">
                {subtitle}
              </span>
            )}
          </div>
          {badge && (
            <ComingSoonBadge label={badge} className="px-1.5 py-0 text-[8px]" />
          )}
        </>
      )}
    </div>
  );

  if (disabled) {
    if (!isExpanded) {
      return (
        <Tooltip content={`${label} — Coming Soon`} placement="right">
          <div>{content}</div>
        </Tooltip>
      );
    }
    return content;
  }

  if (!isExpanded) {
    return (
      <Tooltip content={label} placement="right">
        <Link href={href} aria-label={label}>
          {content}
        </Link>
      </Tooltip>
    );
  }

  return (
    <Link href={href} aria-current={isActive ? "page" : undefined}>
      {content}
    </Link>
  );
}
